"""Generate `assets/fonts/gather_arcade.ttf` — the game's 5x7 bitmap pixel face.

Run it from the repo root: `python tools/make_pixel_font.py`.

The font is generated rather than vendored so the glyphs can be edited here, in
the bitmap tables below, instead of in a binary nobody in this repo can open. It
is also why there is no licence question: nothing was downloaded.

**The 100-unit pixel is the whole design.** Each lit pixel becomes a 100x100 unit
square in a 1000-unit em, so a `font_size` of exactly `10 * N` renders each font
pixel as exactly N screen pixels with no resampling. Any other size lands glyph
edges between screen pixels and the face turns to mush — which is why
`UiTheme.scaled_font()` snaps to a multiple of `UiTheme.FONT_PIXEL` (10) rather
than returning whatever the viewport ratio produced. Changing PX here without
changing that constant breaks the whole arrangement.

Runs on fontTools (`pip install fonttools`); it is a build-time dependency only
and the game never sees it.
"""
