def draw(rows):
    """Return (pen glyph, advance width) for one bitmap."""
    pen = TTGlyphPen(None)
    widest = 0
    for r, row in enumerate(rows):
        y_top = TOP - r * PX
        c = 0
        while c < len(row):
            if row[c] != "1":
                c += 1
                continue
            start = c
            while c < len(row) and row[c] == "1":
                c += 1
            widest = max(widest, c)
            x0, x1 = start * PX, c * PX
            y0, y1 = y_top - PX, y_top
            # Clockwise in a y-up space: up the left edge, across the top, down the right.
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y1))
            pen.lineTo((x1, y1))
            pen.lineTo((x1, y0))
            pen.closePath()
    return pen.glyph(), (widest + 1) * PX


order = [".notdef", "space"] + [f"uni{ord(ch):04X}" for ch in G]
glyphs, metrics, cmap = {}, {}, {}

blank = TTGlyphPen(None)
glyphs[".notdef"] = blank.glyph()
metrics[".notdef"] = (600, 0)
glyphs["space"] = TTGlyphPen(None).glyph()
metrics["space"] = (300, 0)
cmap[0x20] = "space"

for ch, rows in G.items():
    name = f"uni{ord(ch):04X}"
    glyph, adv = draw(rows)
    glyphs[name] = glyph
    metrics[name] = (adv, 0)
    cmap[ord(ch)] = name

fb = FontBuilder(UPM, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({
    "familyName": "Gather Arcade",
    "styleName": "Regular",
    "fullName": "Gather Arcade Regular",
    "psName": "GatherArcade-Regular",
    "version": "Version 1.000",
    "uniqueFontIdentifier": "GatherArcade-Regular-1.000",
})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200,
            sxHeight=500, sCapHeight=700, achVendID="GTHR")
fb.setupPost(isFixedPitch=0)

